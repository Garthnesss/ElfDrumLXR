#!/usr/bin/env python3
"""Generate (or check) the engine writable-state census — Phase 4 (5).

The per-instance state swap needs the exact set of writable global symbols
the engine contributes: every defined BSS/DATA symbol in liblxr_engine.a,
counted PER OBJECT (a file-local static with the same name in two TUs is
two distinct state chunks). The runtime matcher (EngineSwap.cpp) consumes
this table against the host binary's own symbol table and refuses to
engage — falling back to the Phase 0-3 singleton behaviour — unless the
multiset matches exactly.

  gen_census.py generate   rewrite plugin/src/EngineCensus.generated.h
  gen_census.py check      exit 1 if the committed header is stale
Run after any engine rebuild that changes patches/vendor (the state gates
call `check`).
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "plugin" / "src" / "EngineCensus.generated.h"
LIB = ROOT / "plugin" / "build" / "liblxr_engine.a"


def census():
    out = subprocess.run(["nm", "--print-size", str(LIB)],
                         capture_output=True, text=True, check=True).stdout
    entries = []
    seen_globals = set()
    for line in out.splitlines():
        m = re.match(r"^[0-9a-f]+ ([0-9a-f]+) ([BbDd]) (\S+)$", line.strip())
        if not m:
            continue
        size, typ, name = int(m.group(1), 16), m.group(2), m.group(3)
        if typ.isupper():
            # A global can only exist ONCE in a linked binary; a second
            # archive entry with the same name is a weak fallback that the
            # strong definition overrides (mixer_stemData in stubs.c).
            if name in seen_globals:
                continue
            seen_globals.add(name)
        entries.append((name, size))
    entries.sort()
    return entries


def render(entries):
    total = sum(s for _, s in entries)
    lines = [
        "/* GENERATED by tools/gen_census.py from liblxr_engine.a — do not edit.",
        "   The writable-global census the per-instance swap matches against the",
        "   host binary's symbol table at runtime (EngineSwap.cpp). Regenerate",
        "   after any engine patch/vendor change; the gates verify freshness. */",
        "#pragma once",
        "#include <cstddef>",
        "",
        "struct EngineCensusEntry { const char* name; size_t size; };",
        f"inline constexpr size_t kEngineCensusCount = {len(entries)};",
        f"inline constexpr size_t kEngineCensusBytes = {total};",
        "inline const EngineCensusEntry kEngineCensus[] = {",
    ]
    lines += [f'    {{ "{n}", {s} }},' for n, s in entries]
    lines.append("};")
    return "\n".join(lines) + "\n"


def committed_entries():
    text = HEADER.read_text()
    return sorted((n, int(s)) for n, s in
                  re.findall(r'\{ "([^"]+)", (\d+) \}', text))


def main():
    entries = census()
    if len(sys.argv) > 1 and sys.argv[1] == "check":
        if committed_entries() != entries:
            print("CENSUS STALE: committed header differs from liblxr_engine.a "
                  f"({len(committed_entries())} vs {len(entries)} entries) — "
                  "run tools/gen_census.py generate")
            return 1
        print(f"census fresh: {len(entries)} entries, "
              f"{sum(s for _, s in entries)} bytes")
        return 0
    HEADER.write_text(render(entries))
    print(f"wrote {HEADER}: {len(entries)} entries, "
          f"{sum(s for _, s in entries)} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
